library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library pll;
use pll.all;

entity telecran is

    port (
        -- FPGA
        i_clk_50: in std_logic;

        -- HDMI
        io_hdmi_i2c_scl       : inout std_logic;
        io_hdmi_i2c_sda       : inout std_logic;
        o_hdmi_tx_clk        : out std_logic;
        o_hdmi_tx_d          : out std_logic_vector(23 downto 0);
        o_hdmi_tx_de         : out std_logic;
        o_hdmi_tx_hs         : out std_logic;
        i_hdmi_tx_int        : in std_logic;
        o_hdmi_tx_vs         : out std_logic;

        -- KEYs
        i_rst_n : in std_logic;
		  
		-- LEDs
		o_leds : out std_logic_vector(9 downto 0);
		o_de10_leds : out std_logic_vector(7 downto 0);

		-- Coder
		i_left_ch_a : in std_logic;
		i_left_ch_b : in std_logic;
		i_left_pb : in std_logic;
		i_right_ch_a : in std_logic;
		i_right_ch_b : in std_logic;
		i_right_pb : in std_logic
    );
end entity telecran;

architecture rtl of telecran is
	component I2C_HDMI_Config 
		port (
			iCLK : in std_logic;
			iRST_N : in std_logic;
			I2C_SCLK : out std_logic;
			I2C_SDAT : inout std_logic;
			HDMI_TX_INT  : in std_logic
		);
	 end component;
	 
	component pll 
		port (
			refclk : in std_logic;
			rst : in std_logic;
			outclk_0 : out std_logic;
			locked : out std_logic
		);
	end component;

	component hdmi_controler
    generic (
        h_res  : positive := 720;  v_res  : positive := 480;
        h_sync : positive := 61;   h_fp   : positive := 58;  h_bp : positive := 18;
        v_sync : positive := 5;    v_fp   : positive := 30;  v_bp : positive := 9
    );
    port (
        i_clk           : in  std_logic;
        i_rst_n         : in  std_logic;
        o_hdmi_hs       : out std_logic;
        o_hdmi_vs       : out std_logic;
        o_hdmi_de       : out std_logic;
        o_pixel_en      : out std_logic;
        o_pixel_address : out natural range 0 to h_res * v_res - 1;
        o_x_counter     : out natural range 0 to h_res - 1;
        o_y_counter     : out natural range 0 to v_res - 1
    );
	end component;



	component encoder is
	generic (
		register_size : positive := 10;
		DEBOUNCE_TIME : positive := 27000
	);
	port (
		i_clk      : in  std_logic;
		i_rst_n    : in  std_logic;
		i_a        : in  std_logic;
		i_b        : in  std_logic;
		i_pb       : in  std_logic;
		o_position : out std_logic_vector(register_size - 1 downto 0);
		o_pb       : out std_logic
	);
	end component;

	component dpram is 
	generic (
		mem_size    : natural := 720 * 480;
		data_width  : natural := 8
	);
	port (   
		i_clk_a        : in std_logic;
		i_clk_b        : in std_logic;
		i_data_a    : in std_logic_vector(data_width-1 downto 0);
		i_data_b    : in std_logic_vector(data_width-1 downto 0);
		i_addr_a    : in natural range 0 to mem_size-1;
		i_addr_b    : in natural range 0 to mem_size-1;
		i_we_a      : in std_logic := '1';
		i_we_b      : in std_logic := '1';
		o_q_a       : out std_logic_vector(data_width-1 downto 0);
		o_q_b       : out std_logic_vector(data_width-1 downto 0)
   );
   end component;

	constant h_res : natural := 720;
    constant v_res : natural := 480;


	signal s_x_counter : natural range 0 to h_res - 1;
	signal s_y_counter : natural range 0 to v_res - 1;

	signal s_clk_27 : std_logic;
	signal s_rst_n : std_logic;

	signal s_vertical_sync : std_logic_vector(15 downto 0);
	signal s_horizontal_sync : std_logic_vector(15 downto 0);

	signal s_pos_x : natural range 0 to h_res - 1;
	signal s_pos_y : natural range 0 to v_res - 1;

	signal s_addr_a : natural range 0 to h_res * v_res -1;
	signal s_addr_b : natural range 0 to h_res * v_res -1;
	signal s_q_b : std_logic_vector(0 downto 0);
	signal s_cursor : std_logic;

	constant pixel_size : natural := 4;

	signal s_reset_n : std_logic := '1';

	signal s_pb_left : std_logic;
	signal s_pb_right : std_logic;

	signal valor : std_logic_vector(0 downto 0) := "1";

begin
	o_leds <= s_horizontal_sync(9 downto 0);
	o_de10_leds <= (others => '0');
	
	-- Frequency for HDMI is 27MHz generated by this PLL
	pll0 : component pll
		port map (
			refclk => i_clk_50,
			rst => not(i_rst_n),
			outclk_0 => s_clk_27,
			locked => s_rst_n
		);

	-- Configures the ADV7513 for 480p
	I2C_HDMI_Config0 : component I2C_HDMI_Config 
		port map (
			iCLK => i_clk_50,
			iRST_N => i_rst_n,
			I2C_SCLK => io_hdmi_i2c_scl,
			I2C_SDAT => io_hdmi_i2c_sda,
			HDMI_TX_INT => i_hdmi_tx_int
	);

	hdmi_controler0 : component hdmi_controler
    port map (
        i_clk           => s_clk_27,
        i_rst_n         => s_rst_n,
        o_hdmi_hs       => o_hdmi_tx_hs,
        o_hdmi_vs       => o_hdmi_tx_vs,
        o_hdmi_de       => o_hdmi_tx_de,
        o_pixel_en      => open,
        o_pixel_address => s_addr_b,
        o_x_counter     => s_x_counter,
        o_y_counter     => s_y_counter
    );

	o_hdmi_tx_clk <= s_clk_27;

	encoder_horizontal : component encoder
	generic map (register_size => 16)
	port map (
		i_clk      => s_clk_27,
		i_rst_n    => s_rst_n,
		i_a        => i_left_ch_a,
		i_b        => i_left_ch_b,
		i_pb       => i_left_pb,
		o_position => s_horizontal_sync,
		o_pb       => s_pb_left
	);

	encoder_vertical : component encoder
	generic map (register_size => 16)
	port map (
		i_clk      => s_clk_27,
		i_rst_n    => s_rst_n,
		i_a        => i_right_ch_a,
		i_b        => i_right_ch_b,
		i_pb       => i_right_pb,
		o_position => s_vertical_sync,
		o_pb       => s_pb_right
	);

	dpram0 : component dpram
	generic map (
        mem_size   => h_res * v_res,
        data_width => 1
    )
    port map (
        i_clk_a     => s_clk_27,
        i_clk_b     => s_clk_27,
        i_data_a    => valor,
        i_data_b    => "0",
        i_addr_a    => s_addr_a,
        i_addr_b    => s_addr_b,
        i_we_a      => '1',
        i_we_b      => '0',
        o_q_a       => open,
        o_q_b       => s_q_b
    );


	s_pos_x <= (360 + to_integer(signed(s_horizontal_sync))) mod 720;
	s_pos_y <= (240 + to_integer(signed(s_vertical_sync))) mod 480;



	process(s_clk_27, i_rst_n)
	variable v_addr_a : natural range 0 to h_res * v_res - 1 := 0;
	variable controler : std_logic := '0';
	variable v_prev : std_logic := '1';
	begin
		if(i_rst_n = '0') then
			s_addr_a <= 0;
			valor <= "1";
			v_addr_a := 0;
			controler := '0';
			v_prev := '1';
		elsif rising_edge(s_clk_27) then
			if (s_reset_n = '0' and v_prev = '1') then
				controler := '1';
			elsif (controler = '1') then
				s_addr_a <= v_addr_a;
				valor <= "0";
				if (v_addr_a = h_res * v_res - 1) then
					controler := '0';
				end if;
				v_addr_a := (v_addr_a + 1) mod (h_res * v_res);
			else
				s_addr_a <= s_pos_y * h_res + s_pos_x;
				valor <= "1";
			end if;

			
			v_prev := s_reset_n;
		end if;
	end process;

	s_reset_n <= '0' when (s_pb_left = '1' or s_pb_right = '1') else '1';
	

	s_cursor <= '1' when 	(s_x_counter >= s_pos_x and s_x_counter < s_pos_x + pixel_size) and
                    		(s_y_counter >= s_pos_y and s_y_counter < s_pos_y + pixel_size)
            else '0';

	o_hdmi_tx_d <= x"FFFFFF" when (s_cursor = '1' or s_q_b = "1") else x"000000";

end architecture rtl;
